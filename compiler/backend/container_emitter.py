#!/usr/bin/env python3
"""
container_emitter.py
Generates standard OCI Containerfile and .containerignore for agentc applications.
Fully compatible with rootless Podman and Buildah, featuring multi-stage builds,
non-root runtime execution, active PRD/ADR lineage labels, and contract test gates.
"""

import os
from typing import Dict, Any, List, Optional

class ContainerEmitter:
    @staticmethod
    def generate_containerfile(module_name: str, contracts: List[str], target_lang: str,
                               package_options: Dict[str, str], target_options: Dict[str, str],
                               artifacts: Optional[List[Dict[str, Any]]] = None) -> str:
        """Generates an OCI Containerfile for C++20 or Java 21+ targets."""
        artifacts = artifacts or []
        base = package_options.get("base", "alpine").lower()
        tag = package_options.get("tag", "1.0.0")
        safe_mod = module_name.replace(".", "-").lower()
        cname = contracts[0] if contracts else "App"

        # Lineage label
        lineage_parts = []
        for a in artifacts:
            atype = a.get("type", "").upper()
            aid = a.get("id", "")
            lineage_parts.append(f"{atype}:{aid}")
        lineage_str = ",".join(lineage_parts) if lineage_parts else "PRD:Default,ADR:Default"

        if target_lang == "cpp":
            if "distroless" in base:
                builder_img = "docker.io/library/debian:12-slim"
                runtime_img = "gcr.io/distroless/cc-debian12:nonroot"
                setup_builder = "apt-get update && apt-get install -y --no-install-recommends build-essential make && rm -rf /var/lib/apt/lists/*"
            else:
                builder_img = "docker.io/library/alpine:3.23"
                runtime_img = "docker.io/library/alpine:3.23"
                setup_builder = "apk add --no-cache g++ make libstdc++"

            return f"""# ==============================================================================
# Containerfile - Auto-generated by agentc for module {module_name} (target: C++20)
# Compatible with: podman build, buildah build, docker build
# ==============================================================================

# Stage 1: Build & Verification Gate
FROM {builder_img} AS builder
RUN {setup_builder}
WORKDIR /src
COPY . .

# Run contract tests during image build - fails image build if tests fail
RUN make all test
RUN make install PREFIX=/opt/agentc

# Stage 2: Minimal OCI Production Runtime
FROM {runtime_img}
{"RUN apk add --no-cache libstdc++" if "alpine" in base else ""}

LABEL org.opencontainers.image.title="{safe_mod}" \\
      org.opencontainers.image.version="{tag}" \\
      io.agentc.target="cpp" \\
      io.agentc.lineage="{lineage_str}"

COPY --from=builder /opt/agentc /opt/agentc
USER 65532:65532

ENTRYPOINT ["/opt/agentc/bin/{cname}_cli"]
CMD ["selftest"]
"""
        elif target_lang == "java":
            jdk = target_options.get("jdk", "21")
            pkg = target_options.get("package", "com.agentlang.generated")

            if "distroless" in base:
                builder_img = f"docker.io/library/maven:3-eclipse-temurin-{jdk}"
                runtime_img = f"gcr.io/distroless/java{jdk}-debian12:nonroot"
            else:
                builder_img = f"docker.io/library/eclipse-temurin:{jdk}-jdk-alpine"
                runtime_img = f"docker.io/library/eclipse-temurin:{jdk}-jre-alpine"

            return f"""# ==============================================================================
# Containerfile - Auto-generated by agentc for module {module_name} (target: Java {jdk})
# Compatible with: podman build, buildah build, docker build
# ==============================================================================

# Stage 1: Build & Verification Gate
FROM {builder_img} AS builder
WORKDIR /app
COPY . .

# Build application classes and jar
RUN make all

# Stage 2: Minimal OCI Production Runtime
FROM {runtime_img}

LABEL org.opencontainers.image.title="{safe_mod}" \\
      org.opencontainers.image.version="{tag}" \\
      io.agentc.target="java" \\
      io.agentc.lineage="{lineage_str}"

WORKDIR /app
COPY --from=builder /app/target/*.jar /app/app.jar
USER 65532:65532

ENTRYPOINT ["java", "-cp", "/app/app.jar", "{pkg}.{cname}Cli"]
CMD ["selftest"]
"""
        else:
            raise ValueError(f"Unsupported target language for Containerfile: {target_lang}")

    @staticmethod
    def generate_containerignore() -> str:
        return """# Containerignore auto-generated by agentc
.git
.agentc/cache
*.o
*.a
target/
build/
"""
