#!/usr/bin/env python3
"""
cpp_emitter.py
Generates CMakeLists.txt and Makefile for compiling C++20 targets.
Incorporates Drex micro-decision compiler flags, multi-contract support,
CLI harnesses, and installation rules for container/standalone builds.
"""

from typing import Dict, Any, List, Optional, Union

class CppEmitter:
    @staticmethod
    def _normalize_contracts(contract_name_or_list: Union[str, List[str]]) -> List[str]:
        if isinstance(contract_name_or_list, list):
            return contract_name_or_list
        return [contract_name_or_list]

    @staticmethod
    def generate_cmakelists(module_name: str, contracts: Union[str, List[str]], options: Dict[str, str],
                            drex_flags: Optional[List[str]] = None,
                            artifacts: Optional[List[Dict[str, Any]]] = None) -> str:
        contract_list = CppEmitter._normalize_contracts(contracts)
        std = options.get("standard", "c++20").replace("c++", "")
        safe_name = module_name.replace(".", "_").lower()
        flags = " ".join(drex_flags or ["-O2", "-pthread"])

        lineage_comment = "# [agentc] Lineage: "
        if artifacts:
            lineage_comment += ", ".join([f"{a.get('type','').upper()}:{a.get('id','')}" for a in artifacts])
        else:
            lineage_comment += "PRD:Default, ADR:Default"

        targets_block = []
        for cname in contract_list:
            targets_block.append(f"""
# Contract: {cname}
add_library({cname} STATIC {cname}.cpp)
target_include_directories({cname} PUBLIC ${{CMAKE_CURRENT_SOURCE_DIR}})

add_executable({cname}_test {cname}_test.cpp)
target_link_libraries({cname}_test PRIVATE {cname})
add_test(NAME {cname}UnitTest COMMAND {cname}_test)

add_executable({cname}_cli {cname}_cli.cpp)
target_link_libraries({cname}_cli PRIVATE {cname})
""")

        return f"""# ==============================================================================
# CMakeLists.txt - Auto-generated by agentc Compiling Agent
{lineage_comment}
# Reasoning Engine: Drex Micro-Tier (~25 decisions/s single-pass flag selection)
# ==============================================================================
cmake_minimum_required(VERSION 3.20)
project({safe_name} VERSION 1.0.0 LANGUAGES CXX)

set(CMAKE_CXX_STANDARD {std})
set(CMAKE_CXX_STANDARD_REQUIRED ON)
set(CMAKE_CXX_EXTENSIONS OFF)

# Compiler warnings and Drex-selected optimization flags
if(MSVC)
    add_compile_options(/W4 /WX)
else()
    add_compile_options(-Wall -Wextra -pedantic {flags})
endif()

enable_testing()
{''.join(targets_block)}
"""

    @staticmethod
    def generate_makefile(module_name: str, contracts: Union[str, List[str]], options: Dict[str, str],
                          drex_flags: Optional[List[str]] = None,
                          artifacts: Optional[List[Dict[str, Any]]] = None) -> str:
        contract_list = CppEmitter._normalize_contracts(contracts)
        std = options.get("standard", "c++20")
        flags = " ".join(drex_flags or ["-O2", "-pthread"])

        all_libs = " ".join([f"lib{c}.a" for c in contract_list])
        all_tests = " ".join([f"{c}_test" for c in contract_list])
        all_clis = " ".join([f"{c}_cli" for c in contract_list])
        test_cmds = "\n\t".join([f"./{c}_test" for c in contract_list])

        rules = []
        for c in contract_list:
            rules.append(f"""
{c}.o: {c}.cpp {c}.hpp
	$(CXX) $(CXXFLAGS) -c {c}.cpp -o {c}.o

lib{c}.a: {c}.o
	ar rcs lib{c}.a {c}.o

{c}_test: {c}_test.cpp lib{c}.a
	$(CXX) $(CXXFLAGS) {c}_test.cpp -L. -l{c} -o {c}_test

{c}_cli: {c}_cli.cpp lib{c}.a
	$(CXX) $(CXXFLAGS) {c}_cli.cpp -L. -l{c} -o {c}_cli
""")

        return f"""# [agentc] Standalone Makefile (usable with or without CMake)
CXX ?= g++
CXXFLAGS ?= -std={std} -Wall -Wextra {flags}
PREFIX ?= /usr/local

.PHONY: all lib tests cli test clean install

all: {all_libs} {all_tests} {all_clis}

lib: {all_libs}
tests: {all_tests}
cli: {all_clis}

test: {all_tests}
	{test_cmds}
{''.join(rules)}
install: all
	install -d $(DESTDIR)$(PREFIX)/include $(DESTDIR)$(PREFIX)/lib $(DESTDIR)$(PREFIX)/bin
	install -m 644 *.hpp $(DESTDIR)$(PREFIX)/include/
	install -m 644 *.a $(DESTDIR)$(PREFIX)/lib/
	install -m 755 *_cli $(DESTDIR)$(PREFIX)/bin/

clean:
	rm -f *.o *.a *_test *_cli
"""
